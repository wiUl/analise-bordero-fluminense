-- Schema revisado para o projeto Análise de Borderôs do Fluminense FC.
-- Base: SQL exportado do dbdiagram.io e modelo lógico vigente.
-- Execute este arquivo em um schema/banco vazio. Ele não apaga objetos existentes.
-- Regras deliberadamente não impostas: relações entre disponível/devolvido/utilizado,
-- classificação de categoria x plano de sócio e sinais de valores financeiros, até validação
-- de casos reais dos borderôs.

CREATE TABLE adversario (
    id_adversario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR NOT NULL UNIQUE,
    e_classico BOOLEAN NOT NULL,
    e_clube_g12 BOOLEAN NOT NULL
);

CREATE TABLE competicao (
    id_competicao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR NOT NULL UNIQUE
);

CREATE TABLE temporada (
    id_temporada INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano INT NOT NULL UNIQUE
);

CREATE TABLE competicao_temporada (
    id_competicao_temporada INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_competicao INT NOT NULL,
    id_temporada INT NOT NULL,
    CONSTRAINT uq_competicao_temporada UNIQUE (id_competicao, id_temporada),
    CONSTRAINT fk_competicao_temporada_competicao
        FOREIGN KEY (id_competicao) REFERENCES competicao (id_competicao)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_competicao_temporada_temporada
        FOREIGN KEY (id_temporada) REFERENCES temporada (id_temporada)
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE estadio (
    id_estadio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR NOT NULL UNIQUE,
    cidade VARCHAR,
    estado VARCHAR,
    pais VARCHAR,
    capacidade INT,
    CONSTRAINT ck_estadio_capacidade_positiva
        CHECK (capacidade IS NULL OR capacidade > 0)
);

CREATE TABLE setor (
    id_setor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR NOT NULL UNIQUE
);

CREATE TABLE categoria_ingresso (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR NOT NULL UNIQUE
);

CREATE TABLE plano_socio (
    id_plano INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR NOT NULL UNIQUE
);

CREATE TABLE partida (
    id_partida INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL,
    horario TIME,
    adversario_id INT NOT NULL,
    competicao_temporada_id INT NOT NULL,
    estadio_id INT NOT NULL,
    rodada VARCHAR,
    CONSTRAINT fk_partida_adversario
        FOREIGN KEY (adversario_id) REFERENCES adversario (id_adversario)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_partida_competicao_temporada
        FOREIGN KEY (competicao_temporada_id)
        REFERENCES competicao_temporada (id_competicao_temporada)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_partida_estadio
        FOREIGN KEY (estadio_id) REFERENCES estadio (id_estadio)
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE ingresso_partida (
    id_ingresso_partida INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_partida INT NOT NULL,
    id_setor INT NOT NULL,
    id_categoria INT NOT NULL,
    id_plano INT,
    preco DECIMAL(10,2),
    quantidade_disponivel INT,
    quantidade_devolvida INT,
    quantidade_utilizada INT,
    arrecadacao DECIMAL(12,2),
    CONSTRAINT fk_ingresso_partida_partida
        FOREIGN KEY (id_partida) REFERENCES partida (id_partida)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_ingresso_partida_setor
        FOREIGN KEY (id_setor) REFERENCES setor (id_setor)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_ingresso_partida_categoria
        FOREIGN KEY (id_categoria) REFERENCES categoria_ingresso (id_categoria)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_ingresso_partida_plano
        FOREIGN KEY (id_plano) REFERENCES plano_socio (id_plano)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ck_ingresso_preco_nao_negativo
        CHECK (preco IS NULL OR preco >= 0),
    CONSTRAINT ck_ingresso_disponivel_nao_negativo
        CHECK (quantidade_disponivel IS NULL OR quantidade_disponivel >= 0),
    CONSTRAINT ck_ingresso_devolvido_nao_negativo
        CHECK (quantidade_devolvida IS NULL OR quantidade_devolvida >= 0),
    CONSTRAINT ck_ingresso_utilizado_nao_negativo
        CHECK (quantidade_utilizada IS NULL OR quantidade_utilizada >= 0)
);

-- id_plano pode ser NULL. Dois índices parciais impedem duplicidades tanto com plano
-- quanto sem plano, porque UNIQUE comum permite várias linhas com NULL no PostgreSQL.
CREATE UNIQUE INDEX uq_ingresso_partida_sem_plano
    ON ingresso_partida (id_partida, id_setor, id_categoria)
    WHERE id_plano IS NULL;

CREATE UNIQUE INDEX uq_ingresso_partida_com_plano
    ON ingresso_partida (id_partida, id_setor, id_categoria, id_plano)
    WHERE id_plano IS NOT NULL;

CREATE TABLE despesa_partida (
    id_despesa INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_partida INT NOT NULL,
    nome VARCHAR NOT NULL,
    valor DECIMAL(12,2),
    CONSTRAINT fk_despesa_partida_partida
        FOREIGN KEY (id_partida) REFERENCES partida (id_partida)
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE resumo_financeiro_partida (
    id_partida INT PRIMARY KEY,
    total_disponivel INT,
    total_devolvido INT,
    total_utilizado INT,
    arrecadacao_bruta DECIMAL(14,2),
    total_despesas DECIMAL(14,2),
    retencoes DECIMAL(14,2),
    receita_liquida DECIMAL(14,2),
    resultado_final DECIMAL(14,2),
    complemento_contabil DECIMAL(14,2),
    CONSTRAINT fk_resumo_financeiro_partida
        FOREIGN KEY (id_partida) REFERENCES partida (id_partida)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ck_resumo_total_disponivel_nao_negativo
        CHECK (total_disponivel IS NULL OR total_disponivel >= 0),
    CONSTRAINT ck_resumo_total_devolvido_nao_negativo
        CHECK (total_devolvido IS NULL OR total_devolvido >= 0),
    CONSTRAINT ck_resumo_total_utilizado_nao_negativo
        CHECK (total_utilizado IS NULL OR total_utilizado >= 0)
);

CREATE TABLE contexto_partida (
    id_partida INT PRIMARY KEY,
    feriado BOOLEAN,
    dias_desde_ultimo_jogo_maracana INT,
    CONSTRAINT fk_contexto_partida
        FOREIGN KEY (id_partida) REFERENCES partida (id_partida)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ck_contexto_dias_nao_negativo
        CHECK (dias_desde_ultimo_jogo_maracana IS NULL OR dias_desde_ultimo_jogo_maracana >= 0)
);

CREATE TABLE atributos_partida (
    id_partida INT PRIMARY KEY,
    importancia_partida DECIMAL(4,1),
    apelo_adversario DECIMAL(4,1),
    CONSTRAINT fk_atributos_partida
        FOREIGN KEY (id_partida) REFERENCES partida (id_partida)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ck_importancia_partida_escala
        CHECK (importancia_partida IS NULL OR importancia_partida BETWEEN 0 AND 10),
    CONSTRAINT ck_apelo_adversario_escala
        CHECK (apelo_adversario IS NULL OR apelo_adversario BETWEEN 0 AND 10)
);

CREATE TABLE desempenho_partida (
    id_partida INT PRIMARY KEY,
    posicao_fluminense INT,
    pontos_fluminense INT,
    vitorias_ultimos_5 INT,
    empates_ultimos_5 INT,
    derrotas_ultimos_5 INT,
    gols_marcados_ultimos_5 INT,
    gols_sofridos_ultimos_5 INT,
    CONSTRAINT fk_desempenho_partida
        FOREIGN KEY (id_partida) REFERENCES partida (id_partida)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ck_posicao_fluminense_positiva
        CHECK (posicao_fluminense IS NULL OR posicao_fluminense > 0),
    CONSTRAINT ck_pontos_fluminense_nao_negativos
        CHECK (pontos_fluminense IS NULL OR pontos_fluminense >= 0),
    CONSTRAINT ck_vitorias_ultimos_5
        CHECK (vitorias_ultimos_5 IS NULL OR vitorias_ultimos_5 BETWEEN 0 AND 5),
    CONSTRAINT ck_empates_ultimos_5
        CHECK (empates_ultimos_5 IS NULL OR empates_ultimos_5 BETWEEN 0 AND 5),
    CONSTRAINT ck_derrotas_ultimos_5
        CHECK (derrotas_ultimos_5 IS NULL OR derrotas_ultimos_5 BETWEEN 0 AND 5),
    CONSTRAINT ck_gols_marcados_nao_negativos
        CHECK (gols_marcados_ultimos_5 IS NULL OR gols_marcados_ultimos_5 >= 0),
    CONSTRAINT ck_gols_sofridos_nao_negativos
        CHECK (gols_sofridos_ultimos_5 IS NULL OR gols_sofridos_ultimos_5 >= 0)
);

-- Índices em FKs usados em junções. PKs/UNIQUE já possuem índices próprios.
CREATE INDEX ix_partida_adversario ON partida (adversario_id);
CREATE INDEX ix_partida_competicao_temporada ON partida (competicao_temporada_id);
CREATE INDEX ix_partida_estadio ON partida (estadio_id);
-- A restrição UNIQUE (id_competicao, id_temporada) já cobre buscas pelo primeiro campo.
CREATE INDEX ix_competicao_temporada_temporada ON competicao_temporada (id_temporada);
CREATE INDEX ix_ingresso_partida_partida ON ingresso_partida (id_partida);
CREATE INDEX ix_ingresso_partida_setor ON ingresso_partida (id_setor);
CREATE INDEX ix_ingresso_partida_categoria ON ingresso_partida (id_categoria);
CREATE INDEX ix_ingresso_partida_plano ON ingresso_partida (id_plano);
CREATE INDEX ix_despesa_partida_partida ON despesa_partida (id_partida);

-- Notas de modelagem:
-- 1. NULL continua significando valor não informado/não aplicável conforme a documentação.
-- 2. Não há CHECK sobre a soma de devolvidos/utilizados contra disponíveis porque a regra
--    semântica desses campos deve ser confirmada com borderôs reais.
-- 3. Não há CHECK sobre os sinais dos valores monetários, pois ajustes contábeis podem
--    exigir tratamento próprio; preservar a fonte e validar na transformação.
-- 4. Não há ON DELETE CASCADE: registros relacionados não são apagados automaticamente.
